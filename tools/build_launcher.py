"""Build the Windows player launcher, never traverse game/research directories.

Install the pinned build dependency in local/build-tools (or the active build
environment), then run this script on Windows. All cache, spec and generated
hook payload files stay in ignored local/build/launcher.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import subprocess
import sys

try:
    from . import build_release as source_release
except ImportError:
    import build_release as source_release

ROOT = Path(__file__).resolve().parents[1]
PYINSTALLER_VERSION = "6.22.3"
APP_NAME = "KIU Launcher"
DEFAULT_OUTPUT = ROOT / "local/releases/kiu-launcher-windows-preview.zip"
BUILD_ROOT = ROOT / "local/build/launcher"
BUILD_TOOLS = ROOT / "local/build-tools"
PLAYER_TEXT = ("README.md", "STATUS.md", "LICENSE", *source_release.DOC_FILES,
               *source_release.MANIFEST_FILES)
FORBIDDEN_SUFFIXES = {".cci", ".3ds", ".cia", ".cxi", ".sav", ".bin", ".3gx"}
EXCLUDED_MODULES = ("keystone", "kiu.experimental.patch_pitch_limit", "kiu.export_cheats", "tools")


class LauncherBuildError(ValueError):
    """A required component or distribution boundary is invalid."""


def hook_payload_source(root: Path = ROOT) -> bytes:
    """Compile only project-authored hooks, checking canonical exact bytes."""
    sys.path.insert(0, str(root / "src"))
    from kiu.patches import patch_aim_request as aim, pin_reticle as pin
    from kiu.experimental import menu_render_pass as menu
    canonical = json.loads((root / "manifests/gateway_cheats.json").read_text(encoding="utf-8"))
    if canonical["code_sha256"] != aim.CODE_SHA256 or pin.CODE_SHA256 != aim.CODE_SHA256:
        raise LauncherBuildError("canonical hook build hash does not match")
    sites = canonical["features"]["native_mouse_guest_hooks"]["sites"]
    sites += canonical["features"]["menu_bottom_to_top"]["sites"]
    expected = {int(site["address"], 16): site for site in sites}
    payloads = (
        ("GROUND_HOOK", aim.HOOK_VA, aim.assemble_hook()),
        ("RETICLE_HOOK", pin.HOOK_VA, pin.assemble_hook()),
        ("RETICLE_LATE_HOOK", pin.LATE_HOOK_VA, pin.assemble_late_hook()),
        ("MENU_PRE_HOOK", menu.PRE_CAVE, menu.PRE_CAVE_BYTES),
        ("MENU_POST_HOOK", menu.POST_CAVE, menu.POST_CAVE_BYTES),
    )
    lines = ['"""Build-generated project hook instructions; no game image data."""',
             f"BUILD_SHA256 = {aim.CODE_SHA256!r}"]
    for name, address, blob in payloads:
        site = expected.get(address)
        if not site or site["build_sha256"] != aim.CODE_SHA256 or site["replacement_hex"] != blob.hex():
            raise LauncherBuildError(f"{name}: generated bytes differ from canonical manifest")
        lines.append(f"{name} = bytes.fromhex({blob.hex()!r})")
    return ("\n".join(lines) + "\n").encode("utf-8")


def build_environment(root: Path = ROOT, build_tools: Path = BUILD_TOOLS) -> dict[str, str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join((str(build_tools), str(root / "src")))
    env["PYINSTALLER_CONFIG_DIR"] = str(root / "local/build/launcher/cache")
    # Conda's Tcl/Tk can be installed but absent from the interpreter's default
    # DLL/data search paths. These settings affect only this child build.
    prefix = Path(sys.prefix)
    binaries = prefix / "Library/bin"
    if binaries.is_dir():
        env["PATH"] = str(binaries) + os.pathsep + env.get("PATH", "")
    for key, filename, stem in (("TCL_LIBRARY", "init.tcl", "tcl"),
                                ("TK_LIBRARY", "tk.tcl", "tk")):
        for parent in (prefix / "Library/lib", prefix / "tcl"):
            matches = sorted(parent.glob(stem + "*/" + filename))
            if matches:
                env[key] = str(matches[-1].parent)
                break
    return env


def pyinstaller_command(root: Path = ROOT) -> list[str]:
    work = root / "local/build/launcher"
    bootstrap = (
        "import os,sys; from pathlib import Path; "
        "d=Path(sys.prefix)/'Library/bin'; "
        "handle=os.add_dll_directory(str(d)) if hasattr(os,'add_dll_directory') and d.is_dir() else None; "
        "from PyInstaller.__main__ import run; run(sys.argv[1:])"
    )
    command = [sys.executable, "-c", bootstrap, "--onedir", "--windowed", "--noupx",
               "--noconfirm", "--name", APP_NAME, "--contents-directory", "_internal",
               "--workpath", str(work / "work"), "--specpath", str(work / "spec"),
               "--distpath", str(work / "dist"), "--paths", str(root / "src"),
               "--paths", str(work / "generated"), "--hidden-import", "kiu_launcher_payloads",
               "--collect-binaries", "capstone"]
    for name in EXCLUDED_MODULES:
        command += ["--exclude-module", name]
    return [*command, str(root / "run_launcher.py")]


def check_build_environment(root: Path, build_tools: Path) -> None:
    required = ("run_launcher.py", "src/kiu/launcher.py", "src/kiu/launcher_core.py", "src/kiu/game_build.py")
    missing = [name for name in (*required, *PLAYER_TEXT) if not (root / name).is_file()]
    if missing:
        raise LauncherBuildError("missing launcher sources: " + ", ".join(missing))
    result = subprocess.run(
        [sys.executable, "-c", "import PyInstaller; print(PyInstaller.__version__)"],
        env=build_environment(root, build_tools), capture_output=True, text=True,
    )
    if result.returncode or result.stdout.strip() != PYINSTALLER_VERSION:
        detail = result.stderr.strip() or result.stdout.strip()
        raise LauncherBuildError(
            f"PyInstaller {PYINSTALLER_VERSION} is required; install with "
            f"python -m pip install --target local/build-tools pyinstaller=={PYINSTALLER_VERSION}"
            + (f"\nTool check: {detail}" if detail else ""))


def distribution_licenses(name: str) -> dict[str, bytes]:
    dist = importlib.metadata.distribution(name)
    result = {}
    for entry in dist.files or ():
        if "dist-info" in str(entry) and entry.name.upper().startswith(("LICENSE", "COPYING")):
            result[f"licenses/{name}/{entry.name}"] = Path(dist.locate_file(entry)).read_bytes()
    if not result:
        raise LauncherBuildError(f"missing installed license for {name}")
    return result


def runtime_licenses(bundle: Path, build_tools: Path = BUILD_TOOLS) -> dict[str, bytes]:
    """Preserve interpreter/component notices, without publishing local paths."""
    sys.path.insert(0, str(build_tools))
    licenses = {**distribution_licenses("capstone"), **distribution_licenses("pyinstaller")}
    prefix = Path(sys.base_prefix)
    python_license = next((path for path in (prefix / "LICENSE.txt", prefix / "LICENSE_PYTHON.txt")
                           if path.is_file()), None)
    if python_license is None:
        raise LauncherBuildError("Python distribution license is missing")
    licenses["licenses/Python.txt"] = python_license.read_bytes()
    bundled_names = {path.name.lower() for path in bundle.rglob("*") if path.is_file()}
    # Conda records identify the original notices for actual bundled DLLs. No
    # package path/metadata is copied into the player ZIP.
    for metadata in (Path(sys.prefix) / "conda-meta").glob("*.json"):
        record = json.loads(metadata.read_text(encoding="utf-8"))
        if not any(Path(name).name.lower() in bundled_names for name in record.get("files", ())
                   if name.lower().endswith(".dll")):
            continue
        source = Path(record.get("extracted_package_dir", "")) / "info/licenses"
        for notice in source.rglob("*") if source.is_dir() else ():
            if notice.is_file():
                name = notice.relative_to(source).as_posix()
                licenses[f"licenses/{record['name']}/{name}"] = notice.read_bytes()
    for component, stem in (("Tcl", "tcl"), ("Tk", "tk")):
        notices = [path for parent in (Path(sys.prefix) / "tcl", Path(sys.prefix) / "Library/lib")
                   for path in parent.glob(stem + "*/license.terms")]
        if notices:
            licenses[f"licenses/{component}.txt"] = notices[-1].read_bytes()
        elif component == "Tcl" and any(name.startswith("licenses/tk/") for name in licenses):
            pass  # Conda's tk package contains Tcl's original notice.
        else:
            raise LauncherBuildError(f"{component} license terms are missing")
    licenses["THIRD_PARTY_NOTICES.txt"] = (
        "KIU Launcher code is MIT; dependency licenses remain separate.\n"
        "Python, Tcl/Tk, Capstone and PyInstaller notices are included in licenses/.\n"
        "PyInstaller includes a bootloader exception and Apache-2.0 runtime hooks.\n"
        "Keystone is a build-time tool only; its runtime is not bundled.\n"
        "No Azahar or Nintendo game material is included.\n"
        "https://pyinstaller.org/en/stable/license.html\n"
        "https://github.com/capstone-engine/capstone\n"
        "https://www.python.org/psf/license/\n"
    ).encode("utf-8")
    return licenses


def player_files(bundle: Path, root: Path = ROOT, *, licenses: dict[str, bytes]) -> dict[str, bytes]:
    """Only a newly generated onedir tree plus explicit public text files."""
    bundle = bundle.resolve()
    expected = (f"{APP_NAME}.exe", "_internal/base_library.zip",
                "_internal/_tcl_data/init.tcl", "_internal/_tk_data/tk.tcl")
    if any(not (bundle / name).is_file() for name in expected):
        raise LauncherBuildError("incomplete launcher/Tcl/Tk onedir output")
    if not list((bundle / "_internal/capstone").rglob("capstone.dll")):
        raise LauncherBuildError("Capstone runtime DLL is missing")
    files = {}
    for path in sorted(bundle.rglob("*")):
        if path.is_symlink():
            raise LauncherBuildError("symlinks are not allowed in the launcher bundle")
        if not path.is_file():
            continue
        name = path.relative_to(bundle).as_posix()
        if name != f"{APP_NAME}.exe" and not name.startswith("_internal/"):
            raise LauncherBuildError(f"unexpected launcher output: {name}")
        if path.suffix.lower() in FORBIDDEN_SUFFIXES or "keystone" in name.lower():
            raise LauncherBuildError(f"forbidden launcher output: {name}")
        files[name] = path.read_bytes()
    for name in PLAYER_TEXT:
        files[name] = source_release._read_source(root, name)
    files.update(licenses)
    files["SHA256SUMS"] = "".join(
        f"{hashlib.sha256(data).hexdigest()}  {name}\n" for name, data in sorted(files.items())
    ).encode("utf-8")
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--build-tools", type=Path, default=BUILD_TOOLS)
    parser.add_argument("--check", action="store_true", help="check sources, tool version and exact hook payloads")
    args = parser.parse_args(argv)
    try:
        if sys.platform != "win32":
            raise LauncherBuildError("Windows launcher must be built on Windows")
        check_build_environment(ROOT, args.build_tools)
        payloads = hook_payload_source()
        if args.check:
            print(f"Launcher build check passed; PyInstaller {PYINSTALLER_VERSION}, canonical hook bytes match")
            return 0
        generated = BUILD_ROOT / "generated"
        generated.mkdir(parents=True, exist_ok=True)
        (generated / "kiu_launcher_payloads.py").write_bytes(payloads)
        (BUILD_ROOT / "spec").mkdir(parents=True, exist_ok=True)
        result = subprocess.run(pyinstaller_command(), cwd=ROOT, env=build_environment(ROOT, args.build_tools))
        if result.returncode:
            raise LauncherBuildError(f"PyInstaller exited with code {result.returncode}")
        bundle = BUILD_ROOT / "dist" / APP_NAME
        smoke = subprocess.run([str(bundle / f"{APP_NAME}.exe"), "--self-test", "--settings",
                                str(BUILD_ROOT / "qa/preferences.json")], timeout=45)
        if smoke.returncode:
            raise LauncherBuildError(f"frozen launcher self-test exited with code {smoke.returncode}")
        files = player_files(bundle, licenses=runtime_licenses(bundle, args.build_tools))
        source_release.write_release(files, args.output)
        print(f"Wrote {args.output}\nSHA-256: {hashlib.sha256(args.output.read_bytes()).hexdigest()}")
    except (OSError, ValueError, ImportError, KeyError, subprocess.TimeoutExpired) as exc:
        print(f"Launcher build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
